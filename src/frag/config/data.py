class ChainlitPersistenceConfig(BaseSettings):
    """Config for the S3 Bucket and the Dynamo DB table used by chainlit."""

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        frozen=True,
        extra="ignore",
        env_ignore_empty=True,
        validate_default=True,
    )

    # from the .env file
    s3_bucket_name: str = Field(
        validation_alias="aws_s3_chainlit_persistence_bucket_name"
    )
    dynamodb_table_name: str = Field(
        validation_alias="aws_dynamodb_chainlit_persistence_table_name"
    )

    # the value can be different for different resources - so it is permissible to have region configs all over
    s3_region: str = "us-east-1"


class DataProcessingConfig(BaseModel):
    """Config for data processing pipeline."""

    model_config = ConfigDict(frozen=True, validate_default=True)

    # this is the dimensionality of the embedding generated by marqo-fashionSigLIP
    embedding_size: int = 768

    # this is the number of images / texts that are taken in a single batch to generate their embeddings using the embedding model. 512 worked fine.
    embedding_batch_size: int = 512

    # this is the number of datapoints we fetch at one time from the fashion-gen dataset. Best for it to be some integer multiple of the batch size. Not so large that it does not fit in RAM. Without writing image to payload, the process is really fast.
    data_fetch_batch_size: int = 4096

    # this is the batch size - fetched using scroll - that is used during the migration process
    migration_batch_size: int = 1024

    # this is the batch size used during payload updates - used during the payload dictionary update process
    payload_update_batch_size: int = 1024

    # this is the batch size of uploads when uploading the collection to the qdrant db using upload_collection / upload_points
    upload_batch_size: int = 512

    # this is the number of parallel workers used during collection upload
    upload_parallel: int = 4


class VectorDBConfig(BaseModel):
    """Config for setup and use of vector db."""

    model_config = ConfigDict(frozen=True, validate_default=True)

    # this is the url location of the qdrant docker client - this can't actually be an http url since the actual value expected in the receiver is str and it throws an error if I set it as HttpUrl
    vector_store_network_path: str = "http://localhost:6333"

    # qdrant allows two api's - rest and grpc. grpc is more performant while rest api is more convenient. the docs recommend using grpc if we are already familiar with qdrant and are trying to optimize the performance of our application.
    prefer_grpc: bool = True

    # this is the name of the collection in qdrant
    collection_name: str = "fashion_gen"

    # this is the model used to generated embeddings (multi-modal)
    embedding_model: str = "hf-hub:Marqo/marqo-fashionSigLIP"

    # this flag controls if the collection is recreated if it already exists. This will remain true while I have not generated the full collection.
    recreate: bool = False

    # when inserting the embeddings in to qdrant, since they are multi-modal, I am inserting them as named vectors. Below 2 are the names.
    image_vectors_name: str = "images"
    text_vectors_name: str = "texts"

    # this flag controls whether or not we use Memory Map storage in qdrant (also called on-disk storage) from the start - which is recommended for large collections
    vectors_on_disk: bool = True

    # this flag control if we move the Hnsw graph onto the disk or not
    hnsw_on_disk: bool = True

    # this flag controls if we write the payload onto the disk or keep it in memory (RAM)
    payload_on_disk: bool = True

    # this value controls the number of vectors after which we start building HNSW graphs (20k is default)
    indexing_threshold: int = 20000


